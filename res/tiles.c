const unsigned int tileset_data_length = sizeof(tileset_data);

void tiles_load(void) BANKED {
    /* Copy tile data directly to VRAM at 0x8000 without calling
       set_bkg_data, which lives in bank 1 and is inaccessible
       while bank 2 is mapped. Display must be OFF before calling. */
    uint8_t *vram = (uint8_t *)0x8000;
    uint16_t i;
    for (i = 0; i < TILE_COUNT * 16; i++) {
        vram[i] = tileset_data[i];
    }
}

void tiles_load_font_bank1(void) BANKED {
    /* Copy font tiles (ASCII 32-127) into VRAM bank 1.
     * Used by title screen to overlay text on the background image.
     * Caller must set VBK_REG=1 before calling, restore after. */
    uint8_t *vram = (uint8_t *)(0x8000 + TILE_FONT_BASE * 16);
    uint16_t i;
    uint16_t count;
    count = 96 * 16;  /* 96 tiles (32-127), 16 bytes each */
    for (i = 0; i < count; i++) {
        vram[i] = tileset_data[TILE_FONT_BASE * 16 + i];
    }
}
